-- Turkish is verb-final and agglutinative: the templates with the slot first do most
-- of the work. Conjugation rules exist only where the vowel-harmony variants can be
-- listed explicitly; literals are accent-folded (ı->i, ü->u ...), so "-ıyorum" and
-- "-iyorum" are one rule and "-uyorum" / "-üyorum" another.
